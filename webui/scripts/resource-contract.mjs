// Generate only this explicit presentation contract. Never weaken a type to any.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'
const source = readFileSync(new URL('../../schema/resource_contract.schema.json', import.meta.url), 'utf8')
const schema = JSON.parse(source)
function type(node) {
  if (node.$ref) return node.$ref.split('/').at(-1)
  if (node.anyOf) return node.anyOf.map(type).join(' | ')
  if (node.const !== undefined) return JSON.stringify(node.const)
  if (node.enum) return node.enum.map(value => JSON.stringify(value)).join(' | ')
  if (node.type === 'null') return 'null'
  if (node.type === 'string') return 'string'
  if (node.type === 'integer' || node.type === 'number') return 'number'
  if (node.type === 'boolean') return 'boolean'
  if (node.type === 'array') return `Array<${type(node.items)}>`
  if (node.type === 'object') {
    const required = new Set(node.required ?? [])
    const fields = Object.entries(node.properties ?? {}).map(([key, value]) =>
      `  ${JSON.stringify(key)}${required.has(key) ? '' : '?'}: ${type(value)}`).join('\n')
    return `{\n${fields}\n}`
  }
  throw new Error('unsupported resource schema: ' + JSON.stringify(node))
}
const metadataFor = name => Object.fromEntries(Object.entries(schema.$defs[name].properties).map(([key, value]) => {
  const numeric = (value.anyOf ?? [value]).find(entry => entry.type === 'integer')
  return [key, { description: value.description, minimum: numeric?.minimum, default: schema['x-case-defaults'][key] }]
}))
const result = '// Generated by scripts/resource-contract.mjs; edit the Python contract/schema.\n' +
  `// Schema SHA-256: ${createHash('sha256').update(source).digest('hex')}\n` +
  Object.entries(schema.$defs).map(([name, value]) => `export type ${name} = ${type(value)}\n`).join('\n') +
  `\nexport const resourceControlMetadata = ${JSON.stringify(metadataFor('ResourceControls'), null, 2)} as const\n`
const target = new URL('../src/api/resourceContract.generated.ts', import.meta.url)
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== result) throw new Error('resource types stale: npm run contracts:generate')
  process.stdout.write('resource TypeScript contract current\n')
} else {
  writeFileSync(target, result)
  process.stdout.write('wrote ' + fileURLToPath(target) + '\n')
}
